package roundtrip

import (
	"bytes"
	"strings"
	"unicode"
)

const (
	// HeaderPrefix starts line 1 of the generated header; Parse recognizes the header by it.
	HeaderPrefix = "# Generated by dsc-config "
	// HeaderOwnedLine is line 2 of the generated header, matched exactly.
	HeaderOwnedLine = `# Keys under a "dsc-config:owned" marker are re-rendered on every save.`

	headerTool        = "# Generated by dsc-config"
	headerChartSep    = " for chart "
	headerProfileSep  = " from "
	headerHashSep     = " — profile hash "
	headerLineCount   = 3
	headerFieldSpacer = " "
)

// Header is the provenance block dsc-config writes at the top of a generated values.yaml.
type Header struct {
	ToolVersion  string
	ChartVersion string
	Profile      string
	ProfileHash  string
}

// IsZero reports whether no field is set; a zero Header renders and writes nothing.
func (h Header) IsZero() bool {
	return h == Header{}
}

// Render returns the header as LF lines: two comment lines and one blank line, nil when zero.
// An empty field drops its segment of line 1.
func (h Header) Render() []byte {
	if h.IsZero() {
		return nil
	}
	var b strings.Builder
	b.WriteString(headerTool)
	if h.ToolVersion != "" {
		b.WriteString(headerFieldSpacer + h.ToolVersion)
	}
	if h.ChartVersion != "" {
		b.WriteString(headerChartSep + h.ChartVersion)
	}
	if h.Profile != "" {
		b.WriteString(headerProfileSep + h.Profile)
	}
	if h.ProfileHash != "" {
		b.WriteString(headerHashSep + h.ProfileHash)
	}
	b.WriteString("\n" + HeaderOwnedLine + "\n\n")
	return []byte(b.String())
}

// splitHeader splits a leading generated header off src. It returns the raw header bytes
// (nil when src does not start with the full three-line shape), the parsed fields and the rest.
func splitHeader(src []byte) ([]byte, Header, []byte) {
	end := 0
	var lines [headerLineCount]string
	for i := range lines {
		nl := bytes.IndexByte(src[end:], '\n')
		if nl < 0 {
			return nil, Header{}, src
		}
		lines[i] = strings.TrimSuffix(string(src[end:end+nl]), "\r")
		end += nl + 1
	}
	if !strings.HasPrefix(lines[0], HeaderPrefix) || lines[1] != HeaderOwnedLine || lines[2] != "" {
		return nil, Header{}, src
	}
	return src[:end], parseHeaderLine(lines[0]), src[end:]
}

// parseHeaderLine reads the fields of line 1 on a best-effort basis; a field that does not
// parse is left empty.
func parseHeaderLine(line string) Header {
	// Re-adding the prefix's trailing space lets every segment be found by its leading separator.
	s := headerFieldSpacer + strings.TrimPrefix(line, HeaderPrefix)
	var h Header
	if i := strings.LastIndex(s, headerHashSep); i >= 0 {
		h.ProfileHash, s = s[i+len(headerHashSep):], s[:i]
	}
	if i := strings.Index(s, headerProfileSep); i >= 0 {
		h.Profile, s = s[i+len(headerProfileSep):], s[:i]
	}
	if i := strings.Index(s, headerChartSep); i >= 0 {
		h.ChartVersion, s = s[i+len(headerChartSep):], s[:i]
	}
	h.ToolVersion = strings.TrimPrefix(s, headerFieldSpacer)
	h.ToolVersion = singleToken(h.ToolVersion)
	h.ChartVersion = singleToken(h.ChartVersion)
	h.ProfileHash = singleToken(h.ProfileHash)
	return h
}

// singleToken returns s when it holds no whitespace, else "": versions and hashes are one word.
func singleToken(s string) string {
	if strings.IndexFunc(s, unicode.IsSpace) >= 0 {
		return ""
	}
	return s
}
