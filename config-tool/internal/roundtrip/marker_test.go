const (
	// genHeader is a rendered generated header; it shifts body lines by headerLineCount.
	genHeader = "# Generated by dsc-config v0.2.0 for chart 10.16.0\n" + HeaderOwnedLine + "\n\n"
	// featureModelHeader is the header of the FEATURE_MODEL example.
	featureModelHeader = "# Generated by dsc-config 0.4.0 for chart 10.16.0 from .dscprofile.yaml — profile hash 9f2c1a\n" +
		HeaderOwnedLine + "\n\n"
	// badHeader has the header shape, but its fields do not parse.
	badHeader = "# Generated by dsc-config x y\n" + HeaderOwnedLine + "\n\n"
)

// markerSummary is an OwnedMarker with its paths as strings.
type markerSummary struct {
	path  string
	line  int
	ids   []string
	scope []string
}

func summarizeMarkers(ms []OwnedMarker) []markerSummary {
	var out []markerSummary
	for _, m := range ms {
		s := markerSummary{path: m.Path.String(), line: m.Line, ids: m.AnswerIDs}
		for _, p := range m.Scope {
			s.scope = append(s.scope, p.String())
		}
		out = append(out, s)
	}
	return out
}

// ownedLeaves returns the paths of d's leaves that OwnedBy places in a marker's scope.
func ownedLeaves(d *Document, ms []OwnedMarker) []string {
	var out []string
	for _, l := range Classify(d, nil) {
		if _, ok := OwnedBy(ms, l.Path); ok {
			out = append(out, l.Path.String())
		}
	}
	return out
}

func TestOwnedMarkers(t *testing.T) {
	tests := []struct {
		name  string
		src   string
		crlf  bool
		want  []markerSummary
		owned []string
	}{
		{
			name: "feature model example",
			src: featureModelHeader + `decentralizedIam:
  vcAuthentication:
    vcverifier:
      # dsc-config:owned domain.base,did.value
      did: did:web:mp-operations.org
      host: https://verifier.mp-operations.org
`,
			want: []markerSummary{{
				path: "decentralizedIam.vcAuthentication.vcverifier.did", line: 7, ids: []string{"domain.base", "did.value"},
				scope: []string{"decentralizedIam.vcAuthentication.vcverifier.did", "decentralizedIam.vcAuthentication.vcverifier.host"},
			}},
			owned: []string{"decentralizedIam.vcAuthentication.vcverifier.did", "decentralizedIam.vcAuthentication.vcverifier.host"},
		},
		{
			name:  "blank line ends the scope",
			src:   genHeader + "# dsc-config:owned a\nx: 1\ny: 2\n\nz: 3\n",
			want:  []markerSummary{{path: "x", line: 4, ids: []string{"a"}, scope: []string{"x", "y"}}},
			owned: []string{"x", "y"},
		},
		{
			name:  "blank line inside a block scalar",
			src:   genHeader + "# dsc-config:owned a\nx: |\n  one\n\n  two\ny: 2\n",
			want:  []markerSummary{{path: "x", line: 4, ids: []string{"a"}, scope: []string{"x", "y"}}},
			owned: []string{"x", "y"},
		},
		{
			name:  "trailing blank lines of a keep block scalar",
			src:   genHeader + "# dsc-config:owned a\nx: |+\n  one\n\n\ny: 2\n",
			want:  []markerSummary{{path: "x", line: 4, ids: []string{"a"}, scope: []string{"x", "y"}}},
			owned: []string{"x", "y"},
		},
		{
			name:  "blank line inside a nested mapping",
			src:   genHeader + "# dsc-config:owned a\nx:\n  p: 1\n\n  q: 2\ny: 2\n",
			want:  []markerSummary{{path: "x", line: 4, ids: []string{"a"}, scope: []string{"x", "y"}}},
			owned: []string{"x.p", "x.q", "y"},
		},
		{
			name:  "next commented sibling ends the scope",
			src:   genHeader + "# dsc-config:owned a\nx: 1\n# a note\ny: 2\nz: 3\n",
			want:  []markerSummary{{path: "x", line: 4, ids: []string{"a"}, scope: []string{"x"}}},
			owned: []string{"x"},
		},
		{
			name: "next marked sibling starts its own scope",
			src:  genHeader + "# dsc-config:owned a\nx: 1\n# dsc-config:owned b\ny: 2\nz: 3\n",
			want: []markerSummary{
				{path: "x", line: 4, ids: []string{"a"}, scope: []string{"x"}},
				{path: "y", line: 6, ids: []string{"b"}, scope: []string{"y", "z"}},
			},
			owned: []string{"x", "y", "z"},
		},
		{
			name: "nested subtree",
			src: genHeader + `top:
  # dsc-config:owned a
  sub:
    deep:
      leaf: 1
    list: [1, 2]
  other: x
after: 1
`,
			want:  []markerSummary{{path: "top.sub", line: 5, ids: []string{"a"}, scope: []string{"top.sub", "top.other"}}},
			owned: []string{"top.sub.deep.leaf", "top.sub.list[0]", "top.sub.list[1]", "top.other"},
		},
		{
			name: "no header",
			src:  "# dsc-config:owned a\nx: 1\n",
		},
		{
			name: "marker on a sequence item",
			src:  genHeader + "list:\n  # dsc-config:owned a\n  - name: x\n  - # dsc-config:owned b\n    name: y\n",
		},
		{
			name: "marker in a line comment",
			src:  genHeader + "x: 1 # dsc-config:owned a\n",
		},
		{
			name: "marker text inside a block scalar",
			src:  genHeader + "x: |\n  # dsc-config:owned a\ny: 1\n",
		},
		{
			name: "marker below a value is its foot comment",
			src:  genHeader + "x:\n  p: 1\n  # dsc-config:owned a\ny: 1\n",
		},
		{
			name:  "several ids with whitespace",
			src:   genHeader + "#   dsc-config:owned x\n# dsc-config:owned  a , b,,c \nk: 1\n",
			want:  []markerSummary{{path: "k", line: 5, ids: []string{"a", "b", "c"}, scope: []string{"k"}}},
			owned: []string{"k"},
		},
		{
			name:  "CRLF",
			src:   genHeader + "w: 0\n# dsc-config:owned a\nx: 1\ny: 2\n\nz: 3\n",
			crlf:  true,
			want:  []markerSummary{{path: "x", line: 5, ids: []string{"a"}, scope: []string{"x", "y"}}},
			owned: []string{"x", "y"},
		},
		{
			name:  "first top-level key after the header",
			src:   genHeader + "# dsc-config:owned a\nfirst: 1\n",
			want:  []markerSummary{{path: "first", line: 4, ids: []string{"a"}, scope: []string{"first"}}},
			owned: []string{"first"},
		},
		{
			name:  "first key of a nested mapping",
			src:   genHeader + "parent:\n  # dsc-config:owned a\n  key: 1\n  k2: 2\nnext: 3\n",
			want:  []markerSummary{{path: "parent.key", line: 5, ids: []string{"a"}, scope: []string{"parent.key", "parent.k2"}}},
			owned: []string{"parent.key", "parent.k2"},
		},
		{
			name: "blank line between marker and key",
			src:  genHeader + "# dsc-config:owned a\n\nkey: 1\n",
		},
		{
			name:  "unparseable header line",
			src:   badHeader + "# dsc-config:owned a\nk: 1\n",
			want:  []markerSummary{{path: "k", line: 4, ids: []string{"a"}, scope: []string{"k"}}},
			owned: []string{"k"},
		},
		{
			name:  "shadowed sibling is not in scope",
			src:   genHeader + "# dsc-config:owned a\nx: 1\nx: 2\ny: 3\n",
			want:  []markerSummary{{path: "x", line: 4, ids: []string{"a"}, scope: []string{"x", "y"}}},
			owned: []string{"x", "y"},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			src := []byte(tt.src)
			if tt.crlf {
				src = toCRLF(src)
			}
			d := mustParse(t, src)
			ms := d.OwnedMarkers()
			if got := summarizeMarkers(ms); !reflect.DeepEqual(got, tt.want) {
				t.Errorf("OwnedMarkers =\n%+v\nwant\n%+v", got, tt.want)
			}
			if got := ownedLeaves(d, ms); !slices.Equal(got, tt.owned) {
				t.Errorf("owned leaves = %v, want %v", got, tt.owned)
			}
		})
	}
}

func TestOwnedByInnermost(t *testing.T) {
	d := mustParse(t, []byte(genHeader+"# dsc-config:owned outer\ntop:\n  # dsc-config:owned inner\n  a: 1\n  b: 2\n"))
	ms := d.OwnedMarkers()
	for path, want := range map[string]string{"top.a": "inner", "top.b": "inner", "top": "outer"} {
		p, err := ParsePath(path)
		if err != nil {
			t.Fatal(err)
		}
		m, ok := OwnedBy(ms, p)
		if !ok || !slices.Equal(m.AnswerIDs, []string{want}) {
			t.Errorf("OwnedBy(%s) = %v, %v; want %s", path, m.AnswerIDs, ok, want)
		}
	}
	if _, ok := OwnedBy(ms, Path{Key("other")}); ok {
		t.Error("OwnedBy(other) is owned")
	}
}

func TestFileLine(t *testing.T) {
	tests := []struct {
		name      string
		src       string
		generated bool
	}{
		{name: "header", src: genHeader + "first: 1\n", generated: true},
		{name: "no header", src: "first: 1\n"},
		{name: "unparseable header", src: badHeader + "first: 1\n", generated: true},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			d := mustParse(t, []byte(tt.src))
			leaf := Classify(d, nil)[0]
			want := leaf.Line
			if tt.generated {
				want += headerLineCount
			}
			if leaf.Line != 1 || d.FileLine(leaf.Line) != want || d.Generated() != tt.generated {
				t.Errorf("Leaf.Line = %d, FileLine = %d, Generated = %v; want 1, %d, %v",
					leaf.Line, d.FileLine(leaf.Line), d.Generated(), want, tt.generated)
			}
			d.SetHeader(Header{})
			if d.FileLine(leaf.Line) != want || d.Generated() != tt.generated {
				t.Errorf("after SetHeader: FileLine = %d, Generated = %v", d.FileLine(leaf.Line), d.Generated())
			}
		})
	}
}
