const (
	fixtureBundles  = "../model/testdata/bundles"
	fixtureVersion  = "1.0.0"
	roundtripData   = "../roundtrip/testdata/"
	headerLineCount = 3
	// header is the generated header for the fixture bundle's chart version.
	header        = "# Generated by dsc-config v0.2.0 for chart " + fixtureVersion + "\n" + roundtrip.HeaderOwnedLine + "\n\n"
	unknownHeader = "# Generated by dsc-config v0.2.0 for chart 9.9.9\n" + roundtrip.HeaderOwnedLine + "\n\n"
)

func fixtureBundleList(t *testing.T) []model.Bundle {
	t.Helper()
	b, err := model.Versions(os.DirFS(fixtureBundles))
	if err != nil {
		t.Fatal(err)
	}
	return b
}

func readFile(t *testing.T, path string) []byte {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return b
}

// leafWant is the expected class and note of one leaf; an empty note means none.
type leafWant struct {
	class string
	note  string
}

// answerWant is the expected value and origin of one answer.
type answerWant struct {
	value any
	from  Origin
	paths []string
}

func TestLoad(t *testing.T) {
	bundles := fixtureBundleList(t)
	tests := []struct {
		name          string
		src           string
		wantFrom      VersionSource
		wantGenerated bool
		leaves        map[string]leafWant
		answers       map[string]answerWant
		underived     []string
		lines         map[string]int
		skipped       []Entry
	}{
		{
			name: "no markers gives recognized and unknown",
			src: "did:\n  enabled: true\n" +
				"keycloak:\n  ingress:\n    hostname: keycloak.example.org\n" +
				"registration:\n  til: 42\n" +
				"other: 1\n",
			wantFrom: FromLatest,
			leaves: map[string]leafWant{
				"did.enabled":               {class: "recognized"},
				"keycloak.ingress.hostname": {class: "recognized"},
				"registration.til":          {class: "recognized"},
				"other":                     {class: "unknown"},
			},
			answers: map[string]answerWant{
				"identity.did.enabled": {value: true, from: FromRecognized, paths: []string{"did.enabled"}},
				"domain.base":          {value: "example.org", from: FromRecognized, paths: []string{"keycloak.ingress.hostname"}},
				"registration.til":     {value: int64(42), from: FromRecognized, paths: []string{"registration.til"}},
			},
			lines: map[string]int{"did.enabled": 2, "other": 8},
		},
		{
			name: "generated file with markers gives all three classes",
			src: header +
				"# dsc-config:owned domain.base,identity.did.enabled\n" +
				"keycloak:\n  ingress:\n    hostname: keycloak.example.org\n" +
				"did:\n  enabled: true\n" +
				"\n" +
				"rainbow:\n  enabled: false\n" +
				"extra: x\n",
			wantFrom:      FromHeader,
			wantGenerated: true,
			leaves: map[string]leafWant{
				"keycloak.ingress.hostname": {class: "owned"},
				"did.enabled":               {class: "owned"},
				"rainbow.enabled":           {class: "recognized"},
				"extra":                     {class: "unknown"},
			},
			answers: map[string]answerWant{
				"domain.base":          {value: "example.org", from: FromOwned, paths: []string{"keycloak.ingress.hostname"}},
				"identity.did.enabled": {value: true, from: FromOwned, paths: []string{"did.enabled"}},
				"dsp.rainbow.enabled":  {value: false, from: FromRecognized, paths: []string{"rainbow.enabled"}},
			},
			underived: []string{},
			// File lines: the header's three lines come first.
			lines: map[string]int{"keycloak.ingress.hostname": 4 + headerLineCount, "extra": 10 + headerLineCount},
		},
		{
			name: "first value wins and a later differing leaf is unknown",
			src: "keycloak:\n  ingress:\n    hostname: keycloak.example.org\n" +
				"rainbow:\n  ingress:\n    host: rainbow.other.org\n",
			wantFrom: FromLatest,
			leaves: map[string]leafWant{
				"keycloak.ingress.hostname": {class: "recognized"},
				"rainbow.ingress.host":      {class: "unknown", note: "differs from domain.base = example.org"},
			},
			answers: map[string]answerWant{
				"domain.base": {value: "example.org", from: FromRecognized, paths: []string{"keycloak.ingress.hostname"}},
			},
		},
		{
			name: "agreeing leaves share one answer",
			src: "keycloak:\n  ingress:\n    hostname: keycloak.example.org\n" +
				"rainbow:\n  ingress:\n    host: rainbow.example.org\n",
			wantFrom: FromLatest,
			leaves: map[string]leafWant{
				"keycloak.ingress.hostname": {class: "recognized"},
				"rainbow.ingress.host":      {class: "recognized"},
			},
			answers: map[string]answerWant{
				"domain.base": {value: "example.org", from: FromRecognized,
					paths: []string{"keycloak.ingress.hostname", "rainbow.ingress.host"}},
			},
		},
		{
			name: "type and pattern mismatches are unknown",
			src: "did:\n  enabled: \"true\"\n" +
				"scorpio:\n  enabled: yes\n" +
				"rainbow:\n  enabled: {}\n" +
				"keycloak:\n  ingress:\n    hostname: localhost\n" +
				"registration:\n  til: null\n",
			wantFrom: FromLatest,
			leaves: map[string]leafWant{
				"did.enabled":               {class: "unknown", note: "not a boolean, so it does not answer identity.did.enabled"},
				"scorpio.enabled":           {class: "unknown", note: "not a boolean, so it does not answer data.scorpio.enabled"},
				"rainbow.enabled":           {class: "unknown", note: "not a scalar, so it does not answer dsp.rainbow.enabled"},
				"keycloak.ingress.hostname": {class: "unknown", note: "does not match the pattern of domain.base"},
				"registration.til":          {class: "unknown", note: "null does not answer registration.til"},
			},
			answers: map[string]answerWant{},
		},
		{
			name: "alias and merge-key leaves are unknown",
			src: "flag: &t true\n" +
				"base: &b\n  enabled: true\n" +
				"did:\n  enabled: *t\n" +
				"rainbow:\n  <<: *b\n",
			wantFrom: FromLatest,
			leaves: map[string]leafWant{
				"flag":         {class: "unknown"},
				"base.enabled": {class: "unknown"},
				"did.enabled":  {class: "unknown", note: "an alias is not followed, so it does not answer identity.did.enabled"},
				"rainbow.<<":   {class: "unknown"},
			},
			answers: map[string]answerWant{},
		},
		{
			name:          "header version without a bundle falls back to latest",
			src:           unknownHeader + "did:\n  enabled: false\n",
			wantFrom:      FromLatest,
			wantGenerated: true,
			leaves:        map[string]leafWant{"did.enabled": {class: "recognized"}},
			answers: map[string]answerWant{
				"identity.did.enabled": {value: false, from: FromRecognized, paths: []string{"did.enabled"}},
			},
			lines: map[string]int{"did.enabled": 2 + headerLineCount},
		},
		{
			name: "owned value wins over an earlier recognized leaf",
			src: header +
				"rainbow:\n  ingress:\n    host: rainbow.first.org\n" +
				"\n" +
				"# dsc-config:owned domain.base\n" +
				"keycloak:\n  ingress:\n    hostname: keycloak.example.org\n",
			wantFrom:      FromHeader,
			wantGenerated: true,
			leaves: map[string]leafWant{
				"rainbow.ingress.host":      {class: "unknown", note: "differs from domain.base = example.org"},
				"keycloak.ingress.hostname": {class: "owned"},
			},
			answers: map[string]answerWant{
				"domain.base": {value: "example.org", from: FromOwned, paths: []string{"keycloak.ingress.hostname"}},
			},
			underived: []string{},
		},
		{
			name: "owned leaf keeps its class when it does not answer",
			src: header +
				"# dsc-config:owned domain.base,registration.til,identity.did.enabled\n" +
				"keycloak:\n  ingress:\n    hostname: keycloak.example.org\n" +
				"did:\n  enabled: \"no\"\n",
			wantFrom:      FromHeader,
			wantGenerated: true,
			leaves: map[string]leafWant{
				"keycloak.ingress.hostname": {class: "owned"},
				"did.enabled":               {class: "owned", note: "not a boolean, so it does not answer identity.did.enabled"},
			},
			answers: map[string]answerWant{
				"domain.base": {value: "example.org", from: FromOwned, paths: []string{"keycloak.ingress.hostname"}},
			},
			underived: []string{"registration.til", "identity.did.enabled"},
		},
		{
			name: "marker answer derived only by a recognized leaf is underived",
			src: header +
				"# dsc-config:owned identity.did.enabled\n" +
				"x: 1\n" +
				"\n" +
				"did:\n  enabled: true\n",
			wantFrom:      FromHeader,
			wantGenerated: true,
			leaves: map[string]leafWant{
				"x":           {class: "owned"},
				"did.enabled": {class: "recognized"},
			},
			answers: map[string]answerWant{
				"identity.did.enabled": {value: true, from: FromRecognized, paths: []string{"did.enabled"}},
			},
			underived: []string{"identity.did.enabled"},
		},
		{
			name:     "markers without the header are ignored",
			src:      "# dsc-config:owned identity.did.enabled\ndid:\n  enabled: true\n",
			wantFrom: FromLatest,
			leaves:   map[string]leafWant{"did.enabled": {class: "recognized"}},
			answers: map[string]answerWant{
				"identity.did.enabled": {value: true, from: FromRecognized, paths: []string{"did.enabled"}},
			},
		},
		{
			name:     "shadowed duplicate keys are skipped",
			src:      string(readFile(t, roundtripData+"duplicate-keys.yaml")),
			wantFrom: FromLatest,
			skipped: []Entry{
				{Path: "a", Line: 2, Value: "", Note: "shadowed by line 3"},
				{Path: "c", Line: 5, Value: "", Note: "shadowed by line 7"},
			},
		},
		{
			name:     "non-scalar keys are skipped",
			src:      string(readFile(t, roundtripData+"non-scalar-keys.yaml")),
			wantFrom: FromLatest,
			skipped: []Entry{
				{Path: "*k", Line: 3, Value: "2", Note: "key is not a scalar"},
				{Path: complexKeyLabel, Line: 5, Value: "1", Note: "key is not a scalar"},
				{Path: complexKeyLabel, Line: 7, Value: "", Note: "key is not a scalar"},
			},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			src := []byte(tt.src)
			res, err := Load(src, "values.yaml", bundles, Options{})
			if err != nil {
				t.Fatal(err)
			}
			r := res.Report
			assertInvariants(t, src, res)
			if r.ChartVersionFrom != tt.wantFrom || r.ChartVersion != fixtureVersion || r.Chart != DefaultChart {
				t.Errorf("chart = %s %s from %s, want %s %s from %s",
					r.Chart, r.ChartVersion, r.ChartVersionFrom, DefaultChart, fixtureVersion, tt.wantFrom)
			}
			if (r.ChartVersionNote == "") != (tt.wantFrom == FromHeader) {
				t.Errorf("chartVersionNote = %q with chartVersionFrom %s", r.ChartVersionNote, r.ChartVersionFrom)
			}
			if r.Generated != tt.wantGenerated {
				t.Errorf("generated = %v, want %v", r.Generated, tt.wantGenerated)
			}
			entries := byPath(r)
			for path, want := range tt.leaves {
				got, ok := entries[path]
				if !ok {
					t.Errorf("%s: not reported", path)
					continue
				}
				if got.class != want.class || got.entry.Note != want.note {
					t.Errorf("%s: class %s note %q, want %s note %q", path, got.class, got.entry.Note, want.class, want.note)
				}
			}
			if tt.leaves != nil && len(entries) != len(tt.leaves) {
				t.Errorf("reported %d leaves, want %d", len(entries), len(tt.leaves))
			}
			if tt.answers != nil {
				assertAnswers(t, r.Answers, tt.answers)
			}
			if tt.underived != nil {
				var got []string
				for _, m := range r.Markers {
					got = append(got, m.Underived...)
				}
				if !slices.Equal(got, tt.underived) {
					t.Errorf("underived = %v, want %v", got, tt.underived)
				}
			}
			for path, line := range tt.lines {
				if got := entries[path].entry.Line; got != line {
					t.Errorf("%s: line %d, want %d", path, got, line)
				}
			}
			if tt.skipped != nil && !slices.Equal(r.Skipped, tt.skipped) {
				t.Errorf("skipped = %+v, want %+v", r.Skipped, tt.skipped)
			}
		})
	}
}

// TestChooseBundle tells the header's bundle from the latest one: only the older bundle
// recognizes old.enabled, so the classification shows which rules were applied.
func TestChooseBundle(t *testing.T) {
	const (
		olderVersion  = "1.0.0"
		latestVersion = "2.0.0"
		missing       = "9.9.9"
		body          = "old:\n  enabled: true\n"
		olderBundle   = "chart: " + DefaultChart + "\nversion: " + olderVersion + "\nrevision: 1\nrecognize:\n" +
			"  - {path: old.enabled, answer: old.enabled, stage: features, kind: toggle}\n"
		latestBundle = "chart: " + DefaultChart + "\nversion: " + latestVersion + "\nrevision: 1\n"
	)
	bundles, err := model.Versions(fstest.MapFS{
		olderVersion + "/bundle.yaml":  {Data: []byte(olderBundle)},
		latestVersion + "/bundle.yaml": {Data: []byte(latestBundle)},
	})
	if err != nil {
		t.Fatal(err)
	}
	headerFor := func(chart string) string {
		return roundtrip.HeaderPrefix + "v0.2.0" + chart + "\n" + roundtrip.HeaderOwnedLine + "\n\n"
	}
	tests := []struct {
		name        string
		src         string
		wantVersion string
		wantFrom    VersionSource
		wantNote    string
		wantClass   string
	}{
		{name: "header version with a bundle", src: headerFor(" for chart "+olderVersion) + body,
			wantVersion: olderVersion, wantFrom: FromHeader, wantClass: "recognized"},
		{name: "no header", src: body,
			wantVersion: latestVersion, wantFrom: FromLatest, wantNote: noteNoHeader, wantClass: "unknown"},
		{name: "header without a chart version", src: headerFor("") + body,
			wantVersion: latestVersion, wantFrom: FromLatest, wantNote: noteHeaderNoChart, wantClass: "unknown"},
		{name: "header version without a bundle", src: headerFor(" for chart "+missing) + body,
			wantVersion: latestVersion, wantFrom: FromLatest, wantNote: fmt.Sprintf(noteNoBundle, missing), wantClass: "unknown"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			res, err := Load([]byte(tt.src), "values.yaml", bundles, Options{})
			if err != nil {
				t.Fatal(err)
			}
			r := res.Report
			if r.ChartVersion != tt.wantVersion || r.ChartVersionFrom != tt.wantFrom || r.ChartVersionNote != tt.wantNote {
				t.Errorf("chart %s from %s note %q, want %s from %s note %q",
					r.ChartVersion, r.ChartVersionFrom, r.ChartVersionNote, tt.wantVersion, tt.wantFrom, tt.wantNote)
			}
			if got := byPath(r)["old.enabled"].class; got != tt.wantClass {
				t.Errorf("old.enabled is %s, want %s", got, tt.wantClass)
			}
		})
	}
}

func TestLoadMarkers(t *testing.T) {
	src := header +
		"top: 1\n" +
		"# dsc-config:owned domain.base,dsp.rainbow.enabled\n" +
		"keycloak:\n  ingress:\n    hostname: keycloak.example.org\n"
	res, err := Load([]byte(src), "values.yaml", fixtureBundleList(t), Options{})
	if err != nil {
		t.Fatal(err)
	}
	want := []Marker{{Path: "keycloak", Line: 2 + headerLineCount,
		AnswerIDs: []string{"domain.base", "dsp.rainbow.enabled"}, Underived: []string{"dsp.rainbow.enabled"}}}
	got := res.Report.Markers
	if len(got) != len(want) || got[0].Path != want[0].Path || got[0].Line != want[0].Line ||
		!slices.Equal(got[0].AnswerIDs, want[0].AnswerIDs) || !slices.Equal(got[0].Underived, want[0].Underived) {
		t.Errorf("markers = %+v, want %+v", got, want)
	}
}

