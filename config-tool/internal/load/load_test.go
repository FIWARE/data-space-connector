func TestPreview(t *testing.T) {
	long := string(bytes.Repeat([]byte("é"), maxValuePreview+1))
	tests := []struct {
		name, src, want string
	}{
		{name: "scalar", src: "a: hello\n", want: "hello"},
		{name: "long scalar", src: "a: " + long + "\n", want: long[:2*maxValuePreview] + ellipsis},
		{name: "multi-line scalar", src: "a: |\n  one\n  two\n", want: "one" + ellipsis},
		{name: "single line with final newline", src: "a: |\n  one\n", want: "one"},
		{name: "alias", src: "x: &n 1\na: *n\n", want: "*n"},
		{name: "empty collection", src: "a: {}\n", want: ""},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			res, err := Load([]byte(tt.src), "v.yaml", fixtureBundleList(t), Options{})
			if err != nil {
				t.Fatal(err)
			}
			if got := byPath(res.Report)["a"].entry.Value; got != tt.want {
				t.Errorf("value = %q, want %q", got, tt.want)
			}
		})
	}
}

// classified is a reported leaf with the list it is in.
type classified struct {
	class string
	entry Entry
}

func byPath(r Report) map[string]classified {
	m := map[string]classified{}
	for class, list := range map[string][]Entry{"owned": r.Owned, "recognized": r.Recognized, "unknown": r.Unknown} {
		for _, e := range list {
			m[e.Path] = classified{class: class, entry: e}
		}
	}
	return m
}

func assertAnswers(t *testing.T, got []Answer, want map[string]answerWant) {
	t.Helper()
	if len(got) != len(want) {
		t.Errorf("answers = %+v, want %d", got, len(want))
	}
	for _, a := range got {
		w, ok := want[a.ID]
		if !ok {
			t.Errorf("unexpected answer %+v", a)
			continue
		}
		if a.Value != w.value || a.From != w.from || !slices.Equal(a.Paths, w.paths) {
			t.Errorf("answer %s = %#v from %s at %v, want %#v from %s at %v",
				a.ID, a.Value, a.From, a.Paths, w.value, w.from, w.paths)
		}
	}
}

// assertInvariants checks the counts against roundtrip, path uniqueness and an untouched document.
func assertInvariants(t *testing.T, src []byte, res *Result) {
	t.Helper()
	r := res.Report
	leaves, skipped := len(roundtrip.Classify(res.Doc, nil)), len(roundtrip.Skipped(res.Doc))
	c := r.Counts
	if c.Owned+c.Recognized+c.Unknown != leaves || c.Skipped != skipped || c.Total != leaves+skipped {
		t.Errorf("counts = %+v, want %d leaves and %d skipped", c, leaves, skipped)
	}
	if len(r.Owned) != c.Owned || len(r.Recognized) != c.Recognized || len(r.Unknown) != c.Unknown || len(r.Skipped) != c.Skipped {
		t.Errorf("list lengths differ from counts %+v", c)
	}
	seen := map[string]bool{}
	for _, list := range [][]Entry{r.Owned, r.Recognized, r.Unknown} {
		for _, e := range list {
			if seen[e.Path] {
				t.Errorf("path %s reported twice", e.Path)
			}
			seen[e.Path] = true
		}
	}
	out, err := res.Doc.Write()
	if err != nil || !bytes.Equal(out, src) {
		t.Errorf("Doc.Write changed the bytes (err %v)", err)
	}
}
